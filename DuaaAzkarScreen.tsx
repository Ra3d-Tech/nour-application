// دالة تنظيف النص العربي للبحث الذكي بدون تشكيل
const normalizeArabic = (text: string): string => {
  if (!text) return '';
  return text
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[\u0640]/g, '')
    .toLowerCase()
    .trim();
};

