export const DhikrScreen = () => {
  const { isDarkMode } = useTheme();
  const { fontScale } = useApp();

  const [selectedCategory, setSelectedCategory] = useState<string>('all');
  const [searchQuery, setSearchQuery] = useState<string>('');
  const [counts, setCounts] = useState<{ [key: number]: number }>({});

  // حالات نافذة التهنئة بالإنجاز
  const [isCelebrationVisible, setIsCelebrationVisible] = useState<boolean>(false);
  const [celebratedCategoryTitle, setCelebratedCategoryTitle] = useState<string>('');
  const completedCategoriesRef = useRef<{ [catId: string]: boolean }>({});

  // اهتزاز لمسي خفيف
  const triggerHaptic = (isComplete = false) => {
    try {
      if (Platform.OS === 'android') {
        Vibration.vibrate(isComplete ? [0, 60, 80, 60] : 12);
      } else {
        Vibration.vibrate();
      }
    } catch (e) {}
  };

  // محرك البحث العربي الشامل
  const filteredList = useMemo(() => {
    const query = normalizeArabic(searchQuery);

    let base = COMPREHENSIVE_DHIKR;
    if (selectedCategory !== 'all' && !query) {
      base = base.filter((i) => i.category === selectedCategory);
    }

    if (!query) return base;

    return COMPREHENSIVE_DHIKR.filter((item) => {
      const matchText = normalizeArabic(item.text).includes(query);
      const matchVirtue = item.virtue ? normalizeArabic(item.virtue).includes(query) : false;
      const matchSource = item.source ? normalizeArabic(item.source).includes(query) : false;
      const matchCat = normalizeArabic(item.categoryTitle).includes(query);
      return matchText || matchVirtue || matchSource || matchCat;
    });
  }, [searchQuery, selectedCategory]);

  // إحصائيات الإنجاز وحساب اكتمال التارجت للقسم الحالي
  const progressStats = useMemo(() => {
    const list = selectedCategory === 'all'
      ? COMPREHENSIVE_DHIKR
      : COMPREHENSIVE_DHIKR.filter((i) => i.category === selectedCategory);
    if (!list.length) return { percent: 0, completed: 0, total: 0 };
    const completed = list.filter((i) => (counts[i.id] || 0) >= i.count).length;
    return {
      percent: Math.round((completed / list.length) * 100),
      completed,
      total: list.length,
    };
  }, [selectedCategory, counts]);

  // مراقبة إنهاء التارجت لإظهار رسالة التهنئة الفخمة أوتوماتيكياً
  useEffect(() => {
    if (selectedCategory !== 'all' && progressStats.total > 0 && progressStats.percent === 100) {
      if (!completedCategoriesRef.current[selectedCategory]) {
        completedCategoriesRef.current[selectedCategory] = true;
        const currentCatObj = CATEGORIES.find((c) => c.id === selectedCategory);
        setCelebratedCategoryTitle(currentCatObj ? currentCatObj.title : 'الأذكار');
        triggerHaptic(true);
        setTimeout(() => {
          setIsCelebrationVisible(true);
        }, 350);
      }
    }
  }, [progressStats.percent, selectedCategory, progressStats.total]);

  // الضغط على عداد التسبيح
  const handleCountPress = (item: DhikrItem) => {
    const current = counts[item.id] || 0;
    if (current < item.count) {
      const next = current + 1;
      setCounts((prev) => ({ ...prev, [item.id]: next }));
      triggerHaptic(next === item.count);
    }
  };

  // إعادة ضبط أذكار القسم
  const handleResetCategory = () => {
    setCounts((prev) => {
      const next = { ...prev };
      filteredList.forEach((i) => (next[i.id] = 0));
      return next;
    });
    completedCategoriesRef.current[selectedCategory] = false;
  };

  // مشاركة الذكر
  const handleShare = async (item: DhikrItem) => {
    try {
      await Share.share({
        message: `${item.text}\n\n${item.virtue ? 'الفضل: ' + item.virtue + '\n' : ''}${item.source ? 'المصدر: ' + item.source + '\n' : ''}من تطبيق نُور`,
      });
    } catch (e) {}
  };

  // مشاركة إنجاز التارجت
  const handleShareCelebration = async () => {
    try {
      await Share.share({
        message: `الحمد لله، أتممت اليوم قراءة ${celebratedCategoryTitle} كاملة عبر تطبيق نُور 🌿✨ تقبل الله منا ومنكم صالح الأعمال.`,
      });
    } catch (e) {}
  };

  // ألوان فاخرة بدون أي حدود
  const colors = {
    bg: isDarkMode ? '#09120E' : '#F4F7F5',
    card: isDarkMode ? '#13221C' : '#FFFFFF',
    textMain: isDarkMode ? '#F1F5F2' : '#182A22',
    textMuted: isDarkMode ? '#8EA79B' : '#5C7468',
    cardSubtle: isDarkMode ? '#182A22' : '#F6F8F7',
    gold: '#D4AF37',
    primary: isDarkMode ? '#14382A' : '#0B4D3C',
    buttonDone: isDarkMode ? '#153A2A' : '#E8F5E9',
    textDone: isDarkMode ? '#34D399' : '#0D6832',
  };

  return (
    <View style={[styles.screen, { backgroundColor: colors.bg }]}>
      {/* هيدر الصفحة الفخم */}
      <View style={[styles.topBar, { backgroundColor: colors.primary }]}>
        <View style={styles.topRow}>
          <View style={styles.titleWrapper}>
            <Text style={[styles.screenTitle, { fontSize: 20 * fontScale, color: colors.gold }]}>
              الأذكار والأدعية
            </Text>
            <MaterialCommunityIcons
              name="book-open-page-variant"
              size={22}
              color={colors.gold}
              style={{ marginLeft: 8 }}
            />
          </View>
        </View>

        {/* شريط البحث النظيف والسريع (بدون مايك) */}
        <View style={styles.searchContainer}>
          <TextInput
            style={styles.searchInput}
            placeholder="ابحث في نصوص الأذكار وفضائلها..."
            placeholderTextColor="rgba(255,255,255,0.55)"
            value={searchQuery}
            onChangeText={setSearchQuery}
            textAlign="right"
          />

          {searchQuery.length > 0 ? (
            <TouchableOpacity onPress={() => setSearchQuery('')} hitSlop={{ top: 10, bottom: 10, left: 10, right: 10 }}>
              <Ionicons name="close-circle" size={18} color={colors.gold} />
            </TouchableOpacity>
          ) : (
            <Ionicons name="search" size={18} color={colors.gold} style={{ opacity: 0.85 }} />
          )}
        </View>

        {/* شريط التقدم والإنجاز */}
        {!searchQuery.trim() && (
          <View style={styles.statsCard}>
            <View style={styles.statsRow}>
              <TouchableOpacity onPress={handleResetCategory} style={styles.resetRow}>
                <Ionicons name="refresh-outline" size={13} color={colors.gold} />
                <Text style={[styles.resetLabel, { color: colors.gold }]}>إعادة ضبط التكرار</Text>
              </TouchableOpacity>

              <Text style={styles.progressText}>
                إنجاز {progressStats.completed} من {progressStats.total} ({progressStats.percent}%)
              </Text>
            </View>

            <View style={styles.progressBarTrack}>
              <View
                style={[
                  styles.progressBarFill,
                  { width: `${progressStats.percent}%`, backgroundColor: colors.gold },
                ]}
              />
            </View>
          </View>
        )}
      </View>

      {/* شريط الأقسام */}
      {!searchQuery.trim() && (
        <View style={styles.tabsContainer}>
          <ScrollView
            horizontal
            showsHorizontalScrollIndicator={false}
            contentContainerStyle={styles.tabsList}
          >
            {CATEGORIES.map((cat) => {
              const active = selectedCategory === cat.id;
              return (
                <TouchableOpacity
                  key={cat.id}
                  style={[
                    styles.tabPill,
                    {
                      backgroundColor: active
                        ? colors.primary
                        : isDarkMode
                        ? '#14221C'
                        : '#E7ECE9',
                    },
                  ]}
                  onPress={() => setSelectedCategory(cat.id)}
                  activeOpacity={0.7}
                >
                  <MaterialCommunityIcons
                    name={cat.icon as any}
                    size={16}
                    color={active ? colors.gold : colors.textMuted}
                    style={{ marginLeft: 6 }}
                  />
                  <Text
                    style={[
                      styles.tabText,
                      {
                        color: active ? '#FFFFFF' : colors.textMuted,
                        fontWeight: active ? 'bold' : '600',
                      },
                    ]}
                  >
                    {cat.title}
                  </Text>
                </TouchableOpacity>
              );
            })}
          </ScrollView>
        </View>
      )}

      {/* عدد النتائج عند البحث */}
      {searchQuery.trim().length > 0 && (
        <View style={styles.searchResultBar}>
          <Text style={[styles.searchResultText, { color: colors.textMuted }]}>
            تم العثور على {filteredList.length} ذكر ودعاء
          </Text>
        </View>
      )}

      {/* قائمة كروت الأدعية */}
      <ScrollView
        contentContainerStyle={styles.cardsScroll}
        showsVerticalScrollIndicator={false}
      >
        {filteredList.length === 0 ? (
          <View style={styles.emptyView}>
            <MaterialCommunityIcons name="card-search-outline" size={54} color={colors.gold} />
            <Text style={[styles.emptyTitle, { color: colors.textMain }]}>
              لم نجد أي ذكر مطابق لبحثك
            </Text>
            <Text style={[styles.emptySub, { color: colors.textMuted }]}>
              جرّب البحث بكلمة أخرى مثل: "استغفار" أو "حفظ" أو "تسبيح"
            </Text>
          </View>
        ) : (
          filteredList.map((item) => {
            const current = counts[item.id] || 0;
            const isDone = current >= item.count;

            return (
              <View
                key={item.id}
                style={[
                  styles.card,
                  {
                    backgroundColor: colors.card,
                    opacity: isDone ? 0.95 : 1,
                  },
                ]}
              >
                {/* رأس الكرت */}
                <View style={styles.cardHeader}>
                  <View style={styles.cardActions}>
                    <TouchableOpacity
                      style={[styles.smallIconBtn, { backgroundColor: colors.cardSubtle }]}
                      onPress={() => handleShare(item)}
                      hitSlop={{ top: 8, bottom: 8, left: 8, right: 8 }}
                    >
                      <Ionicons name="share-social-outline" size={16} color={colors.gold} />
                    </TouchableOpacity>

                    {current > 0 && (
                      <TouchableOpacity
                        style={[styles.smallIconBtn, { backgroundColor: colors.cardSubtle }]}
                        onPress={() => {
                          setCounts((prev) => ({ ...prev, [item.id]: 0 }));
                        }}
                        hitSlop={{ top: 8, bottom: 8, left: 8, right: 8 }}
                      >
                        <Ionicons name="refresh-outline" size={16} color={colors.textMuted} />
                      </TouchableOpacity>
                    )}
                  </View>

                  <View style={styles.cardHeaderBadges}>
                    <View style={[styles.categoryPill, { backgroundColor: colors.cardSubtle }]}>
                      <Text style={[styles.categoryPillText, { color: colors.textMuted }]}>
                        {item.categoryTitle}
                      </Text>
                    </View>

                    <View
                      style={[
                        styles.targetPill,
                        {
                          backgroundColor: isDone ? colors.buttonDone : colors.cardSubtle,
                        },
                      ]}
                    >
                      <Text
                        style={[
                          styles.targetPillText,
                          { color: isDone ? colors.textDone : colors.gold },
                        ]}
                      >
                        {isDone ? 'تم الانتهاء' : `${item.count} ${item.count === 1 ? 'مرة' : 'مرات'}`}
                      </Text>
                    </View>
                  </View>
                </View>

                {/* نص الدعاء أو الذكر */}
                <Text
                  style={[
                    styles.dhikrText,
                    {
                      color: colors.textMain,
                      fontSize: 16.5 * fontScale,
                      lineHeight: 31 * fontScale,
                    },
                  ]}
                >
                  {item.text}
                </Text>

                {/* فضل الذكر ومصدره */}
                {(item.virtue || item.source) && (
                  <View style={[styles.virtueContainer, { backgroundColor: colors.cardSubtle }]}>
                    {item.virtue ? (
                      <Text style={[styles.virtueText, { color: colors.gold }]}>
                        {item.virtue}
                      </Text>
                    ) : null}
                    {item.source ? (
                      <Text style={[styles.sourceText, { color: colors.textMuted }]}>
                        {item.source}
                      </Text>
                    ) : null}
                  </View>
                )}

                {/* زر العداد التفاعلي */}
                <TouchableOpacity
                  style={[
                    styles.counterBtn,
                    {
                      backgroundColor: isDone ? colors.buttonDone : colors.primary,
                    },
                  ]}
                  onPress={() => handleCountPress(item)}
                  activeOpacity={0.82}
                >
                  <View style={styles.counterBtnContent}>
                    <Text
                      style={[
                        styles.counterBtnNumber,
                        { color: isDone ? colors.textDone : '#FFFFFF' },
                      ]}
                    >
                      {isDone ? 'تم بحمد الله' : `${current} / ${item.count}`}
                    </Text>
                    <MaterialCommunityIcons
                      name={isDone ? 'check-decagram' : 'fingerprint'}
                      size={20}
                      color={isDone ? colors.textDone : colors.gold}
                      style={{ marginRight: 8 }}
                    />
                  </View>
                </TouchableOpacity>
              </View>
            );
          })
        )}
        <View style={{ height: 100 }} />
      </ScrollView>

      {/* ==================== رسالة إنجاز التارجت الملكية ==================== */}
      <Modal
        visible={isCelebrationVisible}
        transparent={true}
        animationType="slide"
        onRequestClose={() => setIsCelebrationVisible(false)}
      >
        <View style={styles.modalOverlay}>
          <View style={[styles.celebrationCard, { backgroundColor: colors.card }]}>
            <View style={[styles.celebrationIconBox, { backgroundColor: colors.primary }]}>
              <MaterialCommunityIcons name="star-crescent" size={42} color={colors.gold} />
            </View>

            <Text style={[styles.celebrationCongrats, { color: colors.gold }]}>
              هنيئاً لك! تقبّل الله طاعتكم
            </Text>

            <Text style={[styles.celebrationMainTitle, { color: colors.textMain }]}>
              أتممت بفضل الله جميع {celebratedCategoryTitle} كاملة
            </Text>

            <View style={[styles.hadithBox, { backgroundColor: colors.cardSubtle }]}>
              <Text style={[styles.hadithText, { color: colors.textMain }]}>
                «مَثَلُ الَّذِي يَذْكُرُ رَبَّهُ وَالَّذِي لاَ يَذْكُرُ رَبَّهُ، مَثَلُ الحَيِّ وَالمَيِّتِ»
              </Text>
              <Text style={[styles.hadithSource, { color: colors.textMuted }]}>
                — رواه البخاري ومسلم
              </Text>
            </View>

            {/* أزرار التفاعل مع الإنجاز */}
            <TouchableOpacity
              style={[styles.celebrationShareBtn, { backgroundColor: colors.primary }]}
              onPress={handleShareCelebration}
              activeOpacity={0.8}
            >
              <Ionicons name="share-social-outline" size={18} color="#FFFFFF" style={{ marginLeft: 6 }} />
              <Text style={styles.celebrationShareText}>مشاركة الأجر والإنجاز</Text>
            </TouchableOpacity>

            <TouchableOpacity
              style={[styles.celebrationDoneBtn, { backgroundColor: colors.cardSubtle }]}
              onPress={() => setIsCelebrationVisible(false)}
              activeOpacity={0.7}
            >
              <Text style={[styles.celebrationDoneText, { color: colors.textMain }]}>
                الحمد لله، إغلاق
              </Text>
            </TouchableOpacity>
          </View>
        </View>
      </Modal>
    </View>
  );
};

